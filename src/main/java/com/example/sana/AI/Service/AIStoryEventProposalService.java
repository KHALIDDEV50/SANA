package com.example.sana.AI.Service;

import com.example.sana.AI.Enums.StoryEventProposalField;
import com.example.sana.API.ApiException;
import com.example.sana.DTO.CreativityDomainDTOs.StoryEventDTO;

import com.example.sana.Enums.ChangeOperation;
import com.example.sana.Enums.ChangeTargetType;

import com.example.sana.Model.ChangeProposalItem;
import com.example.sana.Model.ProjectNode;
import com.example.sana.Model.ProjectOutput;
import com.example.sana.Model.CreativityDomainModels.StoryEvent;

import com.example.sana.Repository.ProjectNodeRepository;
import com.example.sana.Repository.ProjectOutputRepository;
import com.example.sana.Repository.CreativityDomainRepository.StoryEventRepository;

import com.example.sana.Service.CreativityDomainServise.StoryEventService;

import jakarta.validation.ConstraintViolation;
import jakarta.validation.Validator;

import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Service;

import tools.jackson.core.JacksonException;
import tools.jackson.databind.json.JsonMapper;

import java.util.LinkedHashMap;
import java.util.Map;
import java.util.Objects;
import java.util.Set;

@Service
@RequiredArgsConstructor
public class AIStoryEventProposalService {

    private final StoryEventService storyEventService;
    private final StoryEventRepository storyEventRepository;
    private final ProjectNodeRepository projectNodeRepository;
    private final ProjectOutputRepository projectOutputRepository;

    private final JsonMapper jsonMapper;
    private final Validator validator;


    // =====================================================
    // CREATE STORY EVENT
    // =====================================================

    // Validate a creation proposal without saving any records.
    // The approval service runs this before applying changes.
    public void validateCreate(Integer projectId, ChangeProposalItem item) {
        prepareCreate(projectId, item);
    }


    // Create the event only after explicit user approval.
    // The parent approval service manages the transaction.
    public void applyCreate(Integer projectId, ChangeProposalItem item) {

        // Validate again before executing the approved operation.
        PreparedCreate prepared = prepareCreate(projectId, item);

        // Reuse the existing Creativity Domain service.
        // It creates both the ProjectNode and StoryEvent.
        storyEventService.addStoryEvent(prepared.outputId(), prepared.dto());
    }


    // Convert a saved CREATE proposal into a validated DTO.
    private PreparedCreate prepareCreate(Integer projectId, ChangeProposalItem item) {

        // Only a new NODE can be created through this handler.
        requireOperation(item, ChangeOperation.CREATE);

        // Database IDs are generated by the backend.
        // A new event must not reference an existing target.
        if (item.getTargetId() != null || item.getBeforeJson() != null) {

            throw new ApiException("Invalid StoryEvent creation target");
        }

        // Read the exact proposal structure stored by SANA.
        Map<String, Object> after = readProposal(item);

        // A new event requires a destination ProjectOutput.
        Integer outputId = integerValue(after.get("outputId"), false);

        // Prevent creating events in another user's project.
        validateOutput(projectId, outputId);

        // Extract and validate the AI-proposed fields.
        Map<String, Object> fields = extractFields(after);
        validateFieldNames(fields);

        // Create a DTO rather than a JPA Entity.
        StoryEventDTO dto = new StoryEventDTO();

        // Required canvas coordinates.
        dto.setPositionX(finiteDouble(fields.get("positionX")));
        dto.setPositionY(finiteDouble(fields.get("positionY")));

        // Required event details.
        dto.setTitle(requiredText(fields.get("title"), 255));
        dto.setDescription(requiredText(fields.get("description"), 10000));

        // Optional category of the event.
        dto.setEventType(optionalText(fields.get("eventType"), 50));

        // Required narrative presentation order.
        // The existing DTO requires an integer, but does not
        // require this number to be positive.
        dto.setPresentationOrder(integerValue(fields.get("presentationOrder"), true));

        // Optional chronological order.
        // The existing DTO requires a positive value if supplied.
        dto.setChronologicalOrder(optionalPositiveInteger(fields.get("chronologicalOrder")));

        // Optional fictional time and writer notes.
        dto.setInWorldTime(optionalText(fields.get("inWorldTime"), 50));
        dto.setNotes(optionalText(fields.get("notes"), 10000));

        // Apply Jakarta Validation from the existing DTO.
        validateDTO(dto);

        return new PreparedCreate(outputId, dto);
    }


    // =====================================================
    // UPDATE STORY EVENT
    // =====================================================

    // Capture the current event before an UPDATE proposal is saved.
    // This snapshot becomes ChangeProposalItem.beforeJson.
    public String createBeforeSnapshot(Integer projectId, Integer nodeId) {

        // Target IDs represent ProjectNode IDs, not StoryEvent IDs.
        ProjectNode node = projectNodeRepository.findById(nodeId).orElseThrow(() -> new ApiException("StoryEvent node not found"));

        // Confirm the node belongs to the requested project.
        validateNodeProject(projectId, node);

        // Confirm the node is linked to an actual StoryEvent.
        StoryEvent event = getStoryEvent(node);

        // Save plain JSON fields rather than the JPA Entity.
        return toJson(buildSnapshot(node, event));
    }


    // Validate a StoryEvent update without applying changes.
    public void validateUpdate(Integer projectId, ChangeProposalItem item) {
        prepareUpdate(projectId, item);
    }


    // Apply an UPDATE only after the user approves the proposal.
    public void applyUpdate(Integer projectId, ChangeProposalItem item) {

        // Merge the proposed fields into the existing event data.
        PreparedUpdate prepared = prepareUpdate(projectId, item);

        // Reuse the original StoryEventService update method.
        // The DTO contains all existing values plus approved edits.
        storyEventService.updateStoryEvent(prepared.eventId(), prepared.dto());
    }


    // Validate the snapshot and build a complete update DTO.
    private PreparedUpdate prepareUpdate(Integer projectId, ChangeProposalItem item) {

        requireOperation(item, ChangeOperation.UPDATE);

        if (item.getTargetId() == null || item.getTargetId() <= 0) {

            throw new ApiException("StoryEvent target ID is required");
        }

        // Lock the selected canvas node during approval.
        ProjectNode node = projectNodeRepository.findByIdForUpdate(item.getTargetId()).orElseThrow(() -> new ApiException("StoryEvent node not found"));

        validateNodeProject(projectId, node);

        StoryEvent linkedEvent = getStoryEvent(node);

        // ProjectNode and StoryEvent are separate database rows.
        // Lock the StoryEvent record before comparing snapshots.
        StoryEvent event = storyEventRepository.findByIdForUpdate(linkedEvent.getId()).orElseThrow(() -> new ApiException("StoryEvent not found"));

        // Read the original snapshot and proposed new data.
        Map<String, Object> before = readJson(item.getBeforeJson());

        Map<String, Object> after = readProposal(item);

        // If an output ID is provided, it must match the
        // actual output of the selected event.
        if (after.get("outputId") != null) {

            Integer proposedOutputId = integerValue(after.get("outputId"), false);

            if (!Objects.equals(proposedOutputId, node.getProjectOutput().getId())) {

                throw new ApiException("StoryEvent output does not match");
            }
        }

        // Reject outdated proposals.
        // This comparison checks the complete event state,
        // including both timeline ordering fields.
        if (!before.equals(buildSnapshot(node, event))) {

            throw new ApiException("StoryEvent changed after proposal creation. " + "Please review a new proposal");
        }

        Map<String, Object> fields = extractFields(after);

        // Reject unknown field names before applying changes.
        validateFieldNames(fields);

        if (fields.isEmpty()) {
            throw new ApiException("StoryEvent update contains no fields");
        }

        // Copy the complete existing event into a new DTO.
        // This prevents an update to one field from clearing
        // other fields when StoryEventService saves the DTO.
        StoryEventDTO dto = buildDTO(node, event);

        // Apply only the fields explicitly included
        // in the approved proposal.
        for (Map.Entry<String, Object> entry : fields.entrySet()) {

            StoryEventProposalField field;

            try {
                field = StoryEventProposalField.fromFieldName(
                        entry.getKey()
                );
            } catch (IllegalArgumentException e) {
                throw new ApiException("Unsupported StoryEvent field: " + entry.getKey());
            }

            applyField(dto, field, entry.getValue());
        }

        // Validate the complete DTO after merging changes.
        validateDTO(dto);

        return new PreparedUpdate(event.getId(), dto);
    }


    // =====================================================
    // SNAPSHOT AND DTO HELPERS
    // =====================================================

    // Capture all fields relevant to an event update.
    // The snapshot detects changes made after AI suggestions.
    private Map<String, Object> buildSnapshot(ProjectNode node, StoryEvent event) {

        Map<String, Object> snapshot = new LinkedHashMap<>();

        // Snapshot metadata and identity.
        snapshot.put("snapshotType", "STORY_EVENT_V1");
        snapshot.put("nodeId", node.getId());
        snapshot.put("eventId", event.getId());
        snapshot.put("outputId", node.getProjectOutput().getId());

        // Canvas state.
        snapshot.put("nodeType", node.getType());
        snapshot.put("nodeDataJson", node.getDataJson());
        snapshot.put("positionX", node.getPositionX());
        snapshot.put("positionY", node.getPositionY());

        // Actual StoryEvent information.
        snapshot.put("title", event.getTitle());
        snapshot.put("description", event.getDescription());
        snapshot.put("eventType", event.getEventType());

        // Narrative order and real chronological order are
        // independent fields and must both be preserved.
        snapshot.put("presentationOrder", event.getPresentationOrder());
        snapshot.put("chronologicalOrder", event.getChronologicalOrder());

        snapshot.put("inWorldTime", event.getInWorldTime());
        snapshot.put("notes", event.getNotes());

        return snapshot;
    }


    // Build a DTO from the current database state.
    // Unmentioned fields stay unchanged during a partial update.
    private StoryEventDTO buildDTO(ProjectNode node, StoryEvent event) {

        StoryEventDTO dto = new StoryEventDTO();

        // Preserve current canvas coordinates.
        dto.setPositionX(node.getPositionX());
        dto.setPositionY(node.getPositionY());

        // Preserve current StoryEvent fields.
        dto.setTitle(event.getTitle());
        dto.setDescription(event.getDescription());
        dto.setEventType(event.getEventType());

        // Preserve the two distinct timeline positions.
        dto.setPresentationOrder(event.getPresentationOrder());
        dto.setChronologicalOrder(event.getChronologicalOrder());

        dto.setInWorldTime(event.getInWorldTime());
        dto.setNotes(event.getNotes());

        return dto;
    }


    // Apply a single approved field using the enum.
    // Use traditional switch/case/break syntax.
    private void applyField(StoryEventDTO dto, StoryEventProposalField field, Object value) {

        switch (field) {

            case POSITION_X:
                dto.setPositionX(finiteDouble(value));
                break;

            case POSITION_Y:
                dto.setPositionY(finiteDouble(value));
                break;

            case TITLE:
                dto.setTitle(requiredText(value, 255));
                break;

            case DESCRIPTION:
                dto.setDescription(requiredText(value, 10000));
                break;

            case EVENT_TYPE:
                dto.setEventType(optionalText(value, 50));
                break;

            case PRESENTATION_ORDER:
                // This field controls the narrative sequence.
                dto.setPresentationOrder(integerValue(value, true));
                break;

            case CHRONOLOGICAL_ORDER:
                // Null is allowed when the chronological
                // position has not been decided yet.
                dto.setChronologicalOrder(optionalPositiveInteger(value));
                break;

            case IN_WORLD_TIME:
                dto.setInWorldTime(optionalText(value, 50));
                break;

            case NOTES:
                dto.setNotes(optionalText(value, 10000));
                break;

            default:
                throw new ApiException("Unsupported StoryEvent field");
        }
    }


    // =====================================================
    // PROJECT AND ENTITY VALIDATION
    // =====================================================

    // Verify the target output belongs to the selected project.
    private void validateOutput(Integer projectId, Integer outputId) {

        ProjectOutput output = projectOutputRepository.findProjectOutputById(outputId);

        if (projectId == null || output == null || output.getProject() == null || !projectId.equals(output.getProject().getId())) {

            throw new ApiException("Output does not belong to this project");
        }
    }


    // Verify the selected ProjectNode belongs to the project.
    private void validateNodeProject(Integer projectId, ProjectNode node) {

        if (projectId == null || node.getProjectOutput() == null || node.getProjectOutput().getProject() == null || !projectId.equals(node.getProjectOutput().getProject().getId())) {

            throw new ApiException("StoryEvent does not belong to this project");
        }
    }


    // Verify the actual node type in the database.
    // Never trust only the elementType sent by the AI.
    private StoryEvent getStoryEvent(ProjectNode node) {

        if (!"STORY_EVENT".equals(node.getType()) || node.getStoryEvent() == null) {

            throw new ApiException("Selected node is not a StoryEvent");
        }

        return node.getStoryEvent();
    }


    // Confirm the requested proposal operation and target.
    private void requireOperation(ChangeProposalItem item, ChangeOperation expected) {

        if (item == null || item.getOperation() != expected || item.getTargetType() != ChangeTargetType.NODE) {

            throw new ApiException("Invalid StoryEvent proposal operation");
        }
    }


    // =====================================================
    // JSON AND FIELD VALIDATION
    // =====================================================

    // Read and validate the standard saved proposal structure.
    private Map<String, Object> readProposal(ChangeProposalItem item) {

        Map<String, Object> after = readJson(item.getAfterJson());

        if (!after.keySet().equals(Set.of("outputId", "elementType", "fields"))) {

            throw new ApiException("Invalid StoryEvent proposal structure");
        }

        if (!"STORY_EVENT".equals(after.get("elementType"))) {
            throw new ApiException("This handler supports STORY_EVENT only");
        }

        return after;
    }


    // Extract the AI-proposed fields as a plain map.
    private Map<String, Object> extractFields(Map<String, Object> after) {

        if (!(after.get("fields") instanceof Map<?, ?> raw)) {
            throw new ApiException("Invalid StoryEvent fields");
        }

        return stringKeyMap(raw);
    }


    // Reject unknown field names.
    // This prevents the AI from modifying IDs or relationships.
    private void validateFieldNames(Map<String, Object> fields) {

        for (String fieldName : fields.keySet()) {

            if (!StoryEventProposalField.isAllowed(fieldName)) {
                throw new ApiException("Unsupported StoryEvent field: " + fieldName);
            }
        }
    }


    // Reuse Jakarta Validation from StoryEventDTO.
    private void validateDTO(StoryEventDTO dto) {

        Set<ConstraintViolation<StoryEventDTO>> violations = validator.validate(dto);

        if (!violations.isEmpty()) {
            throw new ApiException("Invalid StoryEvent data: " + violations.iterator().next().getMessage());
        }
    }


    // Parse stored JSON without mapping it directly to JPA entities.
    private Map<String, Object> readJson(String json) {

        if (json == null || json.isBlank()) {
            throw new ApiException("Missing StoryEvent proposal data");
        }

        try {
            Map<?, ?> raw = jsonMapper.readValue(json, Map.class);

            if (raw == null) {
                throw new ApiException("Invalid StoryEvent JSON");
            }

            return stringKeyMap(raw);

        } catch (JacksonException e) {
            throw new ApiException("Cannot read StoryEvent JSON");
        }
    }


    // Require string keys in all JSON objects.
    private Map<String, Object> stringKeyMap(Map<?, ?> raw) {

        Map<String, Object> result = new LinkedHashMap<>();

        for (Map.Entry<?, ?> entry : raw.entrySet()) {

            if (!(entry.getKey() instanceof String key)) {
                throw new ApiException("Invalid JSON field name");
            }

            result.put(key, entry.getValue());
        }

        return result;
    }


    // Serialize a plain snapshot, not a Hibernate Entity.
    private String toJson(Map<String, Object> data) {

        try {
            return jsonMapper.writeValueAsString(data);

        } catch (JacksonException e) {
            throw new ApiException("Cannot serialize StoryEvent snapshot");
        }
    }


    // =====================================================
    // VALUE VALIDATION HELPERS
    // =====================================================

    // Required text must not be null, empty or oversized.
    private String requiredText(Object value, int maxLength) {

        if (!(value instanceof String text) || text.isBlank() || text.length() > maxLength) {

            throw new ApiException("Invalid required StoryEvent text");
        }

        return text.trim();
    }


    // Optional text can be null when clearing a field.
    private String optionalText(Object value, int maxLength) {

        if (value == null) {
            return null;
        }

        if (!(value instanceof String text) || text.length() > maxLength) {

            throw new ApiException("Invalid optional StoryEvent text");
        }

        return text;
    }


    // Require a valid integer.
    // When allowNonPositive is false, the value must be positive.
    private Integer integerValue(Object value, boolean allowNonPositive) {

        if (!(value instanceof Number number)) {
            throw new ApiException("StoryEvent integer value is required");
        }

        double n = number.doubleValue();

        if (!Double.isFinite(n) || n < Integer.MIN_VALUE || n > Integer.MAX_VALUE || Math.floor(n) != n) {

            throw new ApiException("Invalid StoryEvent integer value");
        }

        if (!allowNonPositive && n <= 0) {
            throw new ApiException("Value must be positive");
        }

        return number.intValue();
    }

    // Chronological order is optional but must be positive.
    private Integer optionalPositiveInteger(Object value) {

        if (value == null) {
            return null;
        }

        return integerValue(value, false);
    }

    // Reject nonnumeric or infinite canvas coordinates.
    private Double finiteDouble(Object value) {

        if (!(value instanceof Number number)) {
            throw new ApiException("StoryEvent position must be numeric");
        }

        double n = number.doubleValue();

        if (!Double.isFinite(n)) {
            throw new ApiException("Invalid StoryEvent position");
        }

        return n;
    }

    // =====================================================
    // INTERNAL VALIDATED DATA
    // =====================================================

    // Java records only; no new database tables are created.
    private record PreparedCreate(Integer outputId, StoryEventDTO dto) {}

    private record PreparedUpdate(Integer eventId, StoryEventDTO dto) {}
}
