package com.example.sana.AI.Service;

import com.example.sana.AI.DTO.*;
import com.example.sana.AI.Enums.AIReplyType;
import com.example.sana.API.ApiException;
import com.example.sana.Enums.ExecutionStatus;
import com.example.sana.Model.AIInteraction;
import com.example.sana.Model.Project;
import com.example.sana.Model.User;
import com.example.sana.Repository.AIInteractionRepository;
import com.example.sana.Repository.ProjectRepository;
import com.example.sana.Repository.UserRepository;

import tools.jackson.core.JacksonException;
import tools.jackson.databind.json.JsonMapper;

import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.util.ArrayList;
import java.util.Collections;
import java.util.HashSet;
import java.util.List;
import java.util.Set;

@Service
@RequiredArgsConstructor
public class AIConversationService {

    private final AIInteractionRepository aiInteractionRepository;
    private final ProjectRepository projectRepository;
    private final UserRepository userRepository;
    private final JsonMapper objectMapper;

    private static final int MAX_HISTORY_TURNS = 100;


    // Save a completed AI conversation turn
    // Call this only after an actual AI response is received
    @Transactional
    public SanaAIResponseDTO saveCompletedTurn(Integer projectId, Integer authenticatedUserId, Integer parentInteractionId, SanaAIPreparedRequestDTO request, AIReplyType responseType, String assistantMessage, AIFollowUpDTO followUp, String actualModelName) {

        // Verify that the current user owns the project
        Project project = getAuthorizedProject(projectId, authenticatedUserId);

        User user = userRepository.findById(authenticatedUserId).orElseThrow(() -> new ApiException("User not found"));

        if (request == null || !projectId.equals(request.projectId()) || request.mode() == null || request.task() == null || request.message() == null || request.message().isBlank()) {

            throw new ApiException("Invalid prepared AI request");
        }

        if (request.message().length() > 10000) {
            throw new ApiException("AI message is too long");
        }


        if (responseType == null) {
            throw new ApiException("AI response type is required");
        }

        if (assistantMessage == null || assistantMessage.isBlank()) {

            throw new ApiException("AI response cannot be empty");
        }

        if (actualModelName == null || actualModelName.isBlank() || actualModelName.length() > 255) {

            throw new ApiException("Valid AI model name is required");
        }

        // A follow-up question is required when AI asks the user
        if (responseType == AIReplyType.ASK_USER) {

            if (followUp == null || followUp.question() == null || followUp.question().isBlank()) {

                throw new ApiException("AI follow-up question is required");
            }

        } else if (followUp != null) {
            throw new ApiException("Follow-up details are only allowed for ASK_USER");
        }

        // A reply must continue a valid interaction in the same project
        if (parentInteractionId != null) {

            AIInteraction parent = getAuthorizedInteraction(projectId, authenticatedUserId, parentInteractionId);

            if (parent.getStatus() != ExecutionStatus.COMPLETED) {
                throw new ApiException("Cannot continue an incomplete AI interaction");
            }

            AIConversationPayloadDTO parentPayload = readPayload(parent);

            if (parentPayload.mode() != request.mode() || parentPayload.task() != request.task()) {

                throw new ApiException("Conversation mode and task cannot change in a reply");
            }
        }

        // Store structured conversation metadata as JSON
        AIConversationPayloadDTO payload = new AIConversationPayloadDTO(parentInteractionId, request.mode(), request.task(), request.outputId(), request.selectedNodeId(), responseType, assistantMessage, followUp);

        AIInteraction interaction = new AIInteraction();

        interaction.setActionType(request.task().name());
        interaction.setPromptSummary(request.message());
        interaction.setResponseJson(writePayload(payload));
        interaction.setModelName(actualModelName);
        interaction.setStatus(ExecutionStatus.COMPLETED);

        interaction.setUser(user);
        interaction.setProject(project);

        // IDs and timestamps are generated by the database
        AIInteraction saved = aiInteractionRepository.save(interaction);

        return new SanaAIResponseDTO(saved.getId(), request.mode(), request.task(), responseType, assistantMessage, null, followUp);
    }


    // Get the conversation from its latest interaction
    // Results are returned from the oldest to the newest message
    @Transactional(readOnly = true)
    public List<AIConversationTurnDTO> getConversationHistory(Integer projectId, Integer authenticatedUserId, Integer latestInteractionId) {

        getAuthorizedProject(projectId, authenticatedUserId);

        List<AIConversationTurnDTO> history = new ArrayList<>();
        Set<Integer> visitedIds = new HashSet<>();

        Integer currentId = latestInteractionId;

        while (currentId != null) {

            if (history.size() >= MAX_HISTORY_TURNS) {
                throw new ApiException("Conversation exceeds the supported history limit");
            }

            // Detect unexpected circular references
            if (!visitedIds.add(currentId)) {
                throw new ApiException("Invalid circular AI conversation reference");
            }

            AIInteraction interaction = getAuthorizedInteraction(projectId, authenticatedUserId, currentId);

            if (interaction.getStatus() != ExecutionStatus.COMPLETED) {
                throw new ApiException("Conversation contains an incomplete interaction");
            }

            AIConversationPayloadDTO payload = readPayload(interaction);

            history.add(new AIConversationTurnDTO(interaction.getId(), payload.parentInteractionId(), interaction.getCreatedAt(), payload.mode(), payload.task(), payload.outputId(), payload.selectedNodeId(), interaction.getPromptSummary(), payload.assistantMessage(), payload.responseType(), payload.followUp()));

            // Move to the previous interaction
            currentId = payload.parentInteractionId();
        }

        // We traversed backward; return chronological order
        Collections.reverse(history);

        return history;
    }


    // Verify project ownership before reading conversation data
    private Project getAuthorizedProject(Integer projectId, Integer authenticatedUserId) {

        if (projectId == null || authenticatedUserId == null) {
            throw new ApiException("Project and user are required");
        }

        Project project = projectRepository.findById(projectId).orElseThrow(() -> new ApiException("Project not found"));

        if (project.getOwner() == null || !authenticatedUserId.equals(project.getOwner().getId())) {

            throw new ApiException("Access denied to this project");
        }

        return project;
    }


    // A conversation turn must belong to the same user and project
    private AIInteraction getAuthorizedInteraction(Integer projectId, Integer authenticatedUserId, Integer interactionId) {

        AIInteraction interaction = aiInteractionRepository.findById(interactionId).orElseThrow(() -> new ApiException("AI interaction not found"));

        if (!projectId.equals(interaction.getProject().getId()) || !authenticatedUserId.equals(interaction.getUser().getId())) {

            throw new ApiException("AI interaction does not belong to this conversation");
        }

        return interaction;
    }


    // Convert conversation metadata into JSON for responseJson
    private String writePayload(AIConversationPayloadDTO payload) {

        try {
            return objectMapper.writeValueAsString(payload);

        } catch (JacksonException e) {
            throw new ApiException("Failed to serialize AI conversation");
        }
    }


    // Read conversation metadata from an existing interaction
    private AIConversationPayloadDTO readPayload(AIInteraction interaction) {

        if (interaction.getResponseJson() == null || interaction.getResponseJson().isBlank()) {

            throw new ApiException("AI interaction has no conversation data");
        }

        try {
            AIConversationPayloadDTO payload = objectMapper.readValue(interaction.getResponseJson(), AIConversationPayloadDTO.class);

            if (payload == null || payload.mode() == null || payload.task() == null || payload.responseType() == null || payload.assistantMessage() == null) {

                throw new ApiException("Invalid saved AI conversation data");
            }

            return payload;

        } catch (JacksonException e) {
            throw new ApiException("Failed to read AI conversation data");
        }
    }
}
