package com.example.sana.AI.Service;

import com.example.sana.AI.Enums.WorldProposalField;
import com.example.sana.API.ApiException;
import com.example.sana.DTO.CreativityDomainDTOs.WorldDTO;

import com.example.sana.Enums.ChangeOperation;
import com.example.sana.Enums.ChangeTargetType;

import com.example.sana.Model.ChangeProposalItem;
import com.example.sana.Model.ProjectOutput;

import com.example.sana.Repository.ProjectOutputRepository;
import com.example.sana.Service.CreativityDomainServise.WorldService;

import jakarta.validation.ConstraintViolation;
import jakarta.validation.Validator;

import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Service;

import tools.jackson.core.JacksonException;
import tools.jackson.databind.json.JsonMapper;

import java.util.LinkedHashMap;
import java.util.Map;
import java.util.Set;

@Service
@RequiredArgsConstructor
public class AIWorldCreationService {

    private final WorldService worldService;
    private final ProjectOutputRepository projectOutputRepository;

    private final JsonMapper jsonMapper;
    private final Validator validator;


    // Validate the world proposal without creating database records.
    // The approval service calls this during its validation phase.
    public void validateWorldCreate(Integer projectId, ChangeProposalItem item) {

        prepareWorld(projectId, item);
    }


    // Create the world only after the user approves the proposal.
    // The calling approval service must already have an active transaction.
    public void createWorld(Integer projectId, ChangeProposalItem item) {

        // Revalidate the proposal immediately before applying it.
        // Never assume previously validated AI data is still valid.
        PreparedWorld prepared = prepareWorld(projectId, item);

        // Reuse the existing Creativity Domain service.
        // It creates both ProjectNode and World using repositories.
        worldService.addWorld(prepared.outputId(), prepared.dto());
    }


    // Read, validate and convert the stored proposal into WorldDTO.
    private PreparedWorld prepareWorld(Integer projectId, ChangeProposalItem item) {
        // A CREATE proposal must have a valid project ID.
        if (projectId == null || projectId <= 0 || item == null) {
            throw new ApiException("Invalid world creation request");
        }

        // World creation is represented as a NODE creation.
        // New database IDs must be generated by the backend.
        if (item.getOperation() != ChangeOperation.CREATE || item.getTargetType() != ChangeTargetType.NODE || item.getTargetId() != null || item.getBeforeJson() != null) {
            throw new ApiException("Only CREATE WORLD proposals are supported");
        }

        // Read the structured data saved in afterJson.
        Map<String, Object> after = readJson(item.getAfterJson());

        // Accept only the proposal structure defined by SANA.
        // Unexpected metadata is rejected instead of ignored.
        if (!after.keySet().equals(Set.of("outputId", "elementType", "fields"))) {
            throw new ApiException("Invalid world proposal structure");
        }

        // This service cannot create characters, locations or rules.
        if (!"WORLD".equals(after.get("elementType"))) {
            throw new ApiException("This handler only supports WORLD");
        }

        // Validate the destination output ID.
        Integer outputId = positiveInteger(after.get("outputId"));

        // Confirm the output belongs to the requested project.
        // An AI proposal must never write into another project.
        ProjectOutput output = projectOutputRepository.findProjectOutputById(outputId);

        if (output == null || output.getProject() == null || !projectId.equals(output.getProject().getId())) {
            throw new ApiException("Output does not belong to this project");
        }

        // Read the fields proposed by the AI.
        Map<String, Object> fields = extractFields(after.get("fields"));

        // Require at least one field, and allow only WorldDTO fields.
        // This blocks IDs, JPA relationships and unknown properties.
        if (fields.isEmpty() || !fields.keySet().stream().allMatch(WorldProposalField::isAllowed)) {
            throw new ApiException("World proposal contains unsupported fields");
        }

        // Build a DTO instead of constructing a JPA Entity.
        WorldDTO dto = new WorldDTO();

        // Required canvas coordinates
        dto.setPositionX(finiteDouble(fields.get("positionX")));
        dto.setPositionY(finiteDouble(fields.get("positionY")));

        // Required world details
        dto.setName(requiredText(fields.get("name"), 50));
        dto.setDescription(requiredText(fields.get("description"), 20000));

        // Optional world-building details
        dto.setHistory(optionalText(fields.get("history"), 20000));
        dto.setLore(optionalText(fields.get("lore"), 20000));
        dto.setAtmosphere(optionalText(fields.get("atmosphere"), 20000));
        dto.setNotes(optionalText(fields.get("notes"), 20000));

        // Apply the validation rules already defined in WorldDTO.
        // This complements our custom field and type validation.
        Set<ConstraintViolation<WorldDTO>> violations = validator.validate(dto);

        if (!violations.isEmpty()) {
            throw new ApiException("Invalid world data: " + violations.iterator().next().getMessage());
        }

        // Return validated data without saving anything.
        return new PreparedWorld(outputId, dto);
    }


    // Parse the proposal JSON into a plain Map.
    // Do not deserialize untrusted AI data directly into a JPA Entity.
    private Map<String, Object> readJson(String json) {

        if (json == null || json.isBlank()) {
            throw new ApiException("Missing world proposal data");
        }

        try {
            Map<?, ?> raw = jsonMapper.readValue(json, Map.class);

            if (raw == null) {
                throw new ApiException("Invalid world proposal JSON");
            }

            return toStringKeyMap(raw);

        } catch (JacksonException e) {
            throw new ApiException("Cannot read world proposal JSON");
        }
    }


    // Extract the proposed fields from the saved JSON.
    private Map<String, Object> extractFields(Object value) {

        if (!(value instanceof Map<?, ?> raw)) {
            throw new ApiException("Invalid world fields");
        }

        return toStringKeyMap(raw);
    }


    // Ensure every field name in a JSON object is a String.
    private Map<String, Object> toStringKeyMap(Map<?, ?> raw) {

        Map<String, Object> result = new LinkedHashMap<>();

        for (Map.Entry<?, ?> entry : raw.entrySet()) {

            if (!(entry.getKey() instanceof String key)) {
                throw new ApiException("Invalid world field name");
            }

            result.put(key, entry.getValue());
        }

        return result;
    }


    // Validate required text and enforce a safe length.
    private String requiredText(Object value, int maxLength) {

        if (!(value instanceof String text) || text.isBlank() || text.length() > maxLength) {
            throw new ApiException("Required world field is missing or invalid");
        }

        return text.trim();
    }


    // Optional fields can be omitted or explicitly set to null.
    private String optionalText(Object value, int maxLength) {

        if (value == null) {
            return null;
        }

        if (!(value instanceof String text) || text.length() > maxLength) {
            throw new ApiException("Invalid optional world field");
        }

        return text;
    }


    // Require a positive integer for the existing output ID.
    private Integer positiveInteger(Object value) {

        if (!(value instanceof Number number)) {
            throw new ApiException("Output ID must be numeric");
        }

        double result = number.doubleValue();

        if (!Double.isFinite(result) || result < 1 || result > Integer.MAX_VALUE || Math.floor(result) != result) {
            throw new ApiException("Invalid output ID");
        }

        return number.intValue();
    }


    // Reject missing, invalid or infinite canvas coordinates.
    private Double finiteDouble(Object value) {

        if (!(value instanceof Number number)) {
            throw new ApiException("World position must be numeric");
        }

        double result = number.doubleValue();

        if (!Double.isFinite(result)) {
            throw new ApiException("Invalid world position");
        }

        return result;
    }


    // Temporary validated data used only inside the service.
    // This Java record does not create a database table.
    private record PreparedWorld(Integer outputId, WorldDTO dto) {}
}
